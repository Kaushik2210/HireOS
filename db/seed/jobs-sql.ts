import { DEMO_COMPANIES, DEMO_DISCOVERED_AT } from "@/db/seed/demo-jobs";
import { idFromFingerprint, companySlug } from "@/lib/jobs/keys";
import { ingestJobs } from "@/services/jobs/ingest";
import type { NormalizedJob } from "@/services/jobs/normalize";
import { DEMO_PROVIDERS } from "@/services/jobs/providers/demo";

const text = (value: string) => `'${value.replace(/'/g, "''")}'`;
const nullable = (value: string | number | null) =>
  value === null ? "null" : typeof value === "number" ? String(value) : text(value);
const array = (items: string[]) =>
  items.length === 0 ? "'{}'::text[]" : `array[${items.map(text).join(", ")}]::text[]`;

function jobRow(job: NormalizedJob): string {
  const slug = companySlug(job.company_name);
  const columns = [
    text(idFromFingerprint(job.fingerprint)),
    `(select id from public.companies where slug = ${text(slug)})`,
    text(job.company_name),
    text(job.source_key),
    nullable(job.external_id),
    text(job.fingerprint),
    text(job.title),
    nullable(job.location),
    nullable(job.work_mode),
    nullable(job.job_type),
    nullable(job.seniority),
    nullable(job.salary_min),
    nullable(job.salary_max),
    nullable(job.salary_currency),
    nullable(job.salary_period),
    text(job.description),
    array(job.requirements),
    array(job.responsibilities),
    array(job.required_skills),
    array(job.preferred_skills),
    nullable(job.min_years),
    nullable(job.apply_url),
    job.posted_at ? `${text(job.posted_at)}::date` : "null",
    `${text(JSON.stringify(job.also_listed_on))}::jsonb`,
    "true",
    `${text(DEMO_DISCOVERED_AT)}::timestamptz`,
  ];
  return `  (${columns.join(", ")})`;
}

/**
 * The demo catalogue as SQL, built by running the real ingestion pipeline over the demo
 * providers. Loaded by `supabase db reset` (supabase/seed.sql) for local and staging
 * databases. Production never loads it, so production has no demo jobs.
 */
export async function generateJobsSeedSql(): Promise<string> {
  const { jobs } = await ingestJobs([...DEMO_PROVIDERS]);

  const companies = DEMO_COMPANIES.map(
    (c) =>
      `  (${text(c.slug)}, ${text(c.name)}, ${text(`https://${c.slug}.example`)}, ${text(c.industry)}, ${text(c.size)}, true)`,
  ).join(",\n");

  return [
    "-- Demo data: fictional companies and jobs. Generated by `npm run seed:generate`; do not edit.",
    "-- Safe to run more than once. Production databases never load this file.",
    "",
    "insert into public.companies (slug, name, website, industry, size_band, is_demo) values",
    `${companies}`,
    "on conflict (slug) do nothing;",
    "",
    "insert into public.jobs (",
    "  id, company_id, company_name, source_key, external_id, fingerprint, title, location,",
    "  work_mode, job_type, seniority, salary_min, salary_max, salary_currency, salary_period,",
    "  description, requirements, responsibilities, required_skills, preferred_skills,",
    "  min_years, apply_url, posted_at, also_listed_on, is_demo, discovered_at",
    ") values",
    jobs.map(jobRow).join(",\n"),
    "on conflict do nothing;",
    "",
  ].join("\n");
}
